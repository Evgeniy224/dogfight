import { Vector2 } from './vector.js';

/**
 * Базова сутність. Усе, що рухається, має позицію, швидкість, кут,
 * радіус (для колізій), стан "живий/мертвий" і тип (kind).
 *
 * Це базовий клас — не створюйте його напряму, використовуйте підкласи
 * (Ship, Bullet, Asteroid, ...). 
 */
export class Entity {
  // Приватний статичний лічильник для унікальних id
  static #nextId = 1;

  // Приватне поле id — доступне лише всередині класу
  #id = Entity.#nextId++;

  constructor(x = 0, y = 0) {
    // Позиція та швидкість як Vector2 (зручніше, ніж пари x/y)
    this.pos = new Vector2(x, y);
    this.vel = new Vector2(0, 0);
    this.angle = 0;
    this.radius = 10;
    this.alive = true;
    this.kind = 'entity';
  }

  /** Публічний гетер для id. Ззовні #id змінити не можна. */
  get id() {
    return this.#id;
  }

  /**
   * Оновлення стану. Викликається кожен крок симуляції.
   * За замовчуванням — просто інтегрує швидкість у позицію.
   * Підкласи перекривають це, якщо треба щось інше.
   */
  update(dt) {
    // pos += vel * dt
    this.pos.x += this.vel.x * dt;
    this.pos.y += this.vel.y * dt;
  }

  /**
   * Малювання. За замовчуванням — нічого.
   * Підкласи перекривають.
   */
  draw(ctx) {
    // Порожньо — базовий Entity не малюється
  }

  /** Позначити сутність як "мертву" (для відкладеного видалення). */
  kill() {
    this.alive = false;
  }
}